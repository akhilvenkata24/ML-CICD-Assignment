"""
Pytest Test Suite for ML Pipeline
Tests data loading, model training, prediction generation, accuracy, and metric persistence.
"""

import os
import json
import numpy as np
import pytest
from sklearn.linear_model import LogisticRegression
from model import load_data, train_model, evaluate_model, save_metrics, run_pipeline


def test_load_data_structure():
    """Verify that dataset is loaded with valid shapes and expected attributes."""
    X_train, X_test, y_train, y_test, target_names, feature_names = load_data()

    # Verify sample counts
    assert len(X_train) == 120, "Training set should contain 120 samples (80% of 150)"
    assert len(X_test) == 30, "Test set should contain 30 samples (20% of 150)"
    assert len(y_train) == 120, "Training labels should match sample count"
    assert len(y_test) == 30, "Test labels should match sample count"

    # Verify feature and target structures
    assert X_train.shape[1] == 4, "Iris dataset must contain 4 feature columns"
    assert len(feature_names) == 4, "Iris dataset must have 4 feature names"
    assert len(target_names) == 3, "Iris dataset must have 3 target class names"
    assert set(np.unique(y_train)) == {0, 1, 2}, "Targets must contain classes 0, 1, 2"


def test_train_model():
    """Verify that model training produces a valid, fitted LogisticRegression instance."""
    X_train, X_test, y_train, y_test, _, _ = load_data()
    model = train_model(X_train, y_train)

    assert isinstance(model, LogisticRegression), "Result must be a LogisticRegression object"
    assert hasattr(model, "coef_"), "Fitted model must have coefficients"
    assert hasattr(model, "intercept_"), "Fitted model must have intercept"
    assert hasattr(model, "classes_"), "Fitted model must specify classes"
    assert len(model.classes_) == 3, "Model must have learned 3 classes"


def test_evaluate_model_predictions():
    """Verify that predictions are generated correctly for test data."""
    X_train, X_test, y_train, y_test, _, _ = load_data()
    model = train_model(X_train, y_train)
    accuracy, predictions = evaluate_model(model, X_test, y_test)

    assert len(predictions) == len(y_test), "Prediction array length must match test sample count"
    assert predictions.dtype in [np.int32, np.int64, int], "Predictions must be integer class labels"
    for pred in predictions:
        assert pred in [0, 1, 2], f"Predicted label {pred} is invalid"


def test_evaluate_model_accuracy():
    """Verify that accuracy is within expected valid range and meets threshold."""
    X_train, X_test, y_train, y_test, _, _ = load_data()
    model = train_model(X_train, y_train)
    accuracy, _ = evaluate_model(model, X_test, y_test)

    assert isinstance(accuracy, float), "Accuracy must be a float"
    assert 0.0 <= accuracy <= 1.0, "Accuracy must be between 0.0 and 1.0"
    # Logistic Regression on Iris achieves > 90% accuracy consistently
    assert accuracy >= 0.90, f"Accuracy {accuracy:.2f} should be at least 0.90"


def test_save_metrics(tmp_path):
    """Verify that save_metrics writes valid JSON with required keys."""
    test_json = tmp_path / "test_metrics.json"
    dummy_accuracy = 0.9667
    metrics = save_metrics(dummy_accuracy, output_file=str(test_json), html_file="nonexistent.html")

    assert os.path.exists(str(test_json)), "Metrics file was not created"
    with open(str(test_json), "r", encoding="utf-8") as f:
        loaded = json.load(f)

    assert loaded["model_name"] == "Logistic Regression"
    assert loaded["dataset_name"] == "Iris Dataset"
    assert loaded["accuracy"] == 0.9667
    assert loaded["accuracy_percent"] == "96.67%"
    assert loaded["ci_cd_status"] == "Successful"
    assert "updated_at" in loaded


def test_full_pipeline_execution():
    """Integration test verifying end-to-end execution of run_pipeline."""
    accuracy, model_instance = run_pipeline()

    assert accuracy >= 0.90, "Pipeline accuracy must be >= 0.90"
    assert isinstance(model_instance, LogisticRegression)
    assert os.path.exists("metrics.json"), "metrics.json must be generated by pipeline"
